function near(url, boxes)
  local p = C[countryCode()] or K[continentCode()] or K.eu
  local r = math.rad
  local function d(b)
    return math.sin(r(b[1] - p[1]) / 2) ^ 2 + math.cos(r(p[1])) * math.cos(r(b[1])) * math.sin(r(b[2] - p[2]) / 2) ^ 2
  end
  table.sort(boxes, function(x, y) return d(x) < d(y) end)
  local sets = {}
  for i, b in ipairs(boxes) do sets[i] = b[3] end
  return ifurlup(url, sets, {selector = 'all', backupSelector = 'all', timeout = '2'})
end
